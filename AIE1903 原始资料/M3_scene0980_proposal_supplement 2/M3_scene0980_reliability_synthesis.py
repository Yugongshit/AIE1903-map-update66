"""Combine Steps 2 and 3 with upstream evidence, then export a JSON handoff.

python M3_scene0980_reliability_synthesis.py scene0980_step1_delivery_v1.zip \
    --anomaly m3_step2_results/anomaly_statistics.csv \
    --quality m3_step3_results/observation_quality.csv \
    --scored scored_candidates.csv

The CSVs are generated by the previously delivered Step 2 and Step 3 scripts.
Only the Python standard library is required for this synthesis.
"""

import argparse
import csv
import io
import json
import math
from pathlib import Path
from zipfile import ZipFile


LABELS = {'INSUFFICIENT_EVIDENCE': 'Insufficient Evidence',
          'NO_SIGNIFICANT_MISMATCH': 'No Significant Mismatch',
          'SUSPECTED_MAP_CHANGE': 'Suspected Map Change',
          'NEEDS_FURTHER_VERIFICATION': 'Needs Further Verification'}


def decide(coverage_gate, anomalous, multi_frame):
    """Use the coverage gate first; keep unknown inputs distinct from negatives."""
    if coverage_gate != 'SUFFICIENT':
        return 'INSUFFICIENT_EVIDENCE'
    if anomalous is True and multi_frame == 'STABLE_SUPPORT':
        return 'SUSPECTED_MAP_CHANGE'
    if anomalous is False and multi_frame == 'NO_PERSISTENT_ANOMALY':
        return 'NO_SIGNIFICANT_MISMATCH'
    return 'NEEDS_FURTHER_VERIFICATION'


def read_csv(path):
    with path.open(encoding='utf-8-sig', newline='') as f:
        return list(csv.DictReader(f))


def read_zip(archive, name):
    member, = [p for p in archive.namelist() if p.rsplit('/',1)[-1] == name]
    return list(csv.DictReader(io.StringIO(archive.read(member).decode('utf-8-sig'))))


def keyed(rows, key):
    indexed = {key(r):r for r in rows}
    if len(indexed) != len(rows):
        raise ValueError('Duplicate IDs prevent an unambiguous evidence join.')
    return indexed


def synthesize(anomalies, qualities, metrics, lane_candidates, scored):
    quality_by_key = keyed(qualities, lambda r:(int(r['frame']), int(r['line']), r['track']))
    map_by_key = keyed(metrics, lambda r:(int(r['frame']), int(r['line_id']), r['track_id']))
    keyed(anomalies, lambda r:(int(r['frame']), int(r['line_id']), r['track']))
    target = sorted([r for r in anomalies if r['track']=='T004'],key=lambda r:int(r['frame']))
    if not target:
        raise ValueError('Missing T004 comparison observations.')
    frames = []
    for row in target:
        key = int(row['frame']), int(row['line_id']), row['track']
        quality = quality_by_key[key]
        mapping = map_by_key[key]
        if quality['effective_coverage'].strip():
            raise ValueError('This run expects the current scene inputs with unknown calibrated coverage.')
        if (int(row['used_points']) != int(quality['geometry_points'])
            or int(row['input_points']) != int(quality['input_points'])
            or not math.isclose(float(row['time_s']),float(quality['time_s']),abs_tol=1e-8)):
            raise ValueError(f'Inconsistent evidence for {key}')
        score, limit = float(row['anomaly_score']),float(row['threshold'])
        if not (math.isfinite(score) and math.isfinite(limit) and score >= 0 and limit > 0):
            raise ValueError(f'Invalid anomaly evidence for {key}')
        frames.append(dict(frame=key[0],line_id=key[1],track=key[2],time_s=float(row['time_s']),
            map_token=mapping['best_map_token'],map_part=int(mapping['best_map_part_id']),
            lateral_residual_m=float(row['lateral_signed_m']),anomaly_score=score,anomaly_threshold=limit,
            above_reference=score>limit,input_points=int(quality['input_points']),used_points=int(quality['geometry_points']),
            geometry_usable_ratio=float(quality['geometry_usable_ratio']),effective_coverage=None,
            local_diagnostic='ABOVE_REFERENCE' if score>limit else 'WITHIN_REFERENCE'))
    if len({(r['map_token'],r['map_part'],r['anomaly_threshold']) for r in frames})!=1:
        raise ValueError('T004 window needs a single map part and a common threshold.')

    top = max(frames,key=lambda r:r['anomaly_score'])
    above = sum(r['above_reference'] for r in frames)
    evidence = 'NO_PERSISTENT_ANOMALY' if not above else 'UNRESOLVED'
    window = dict(record_id='T004_26_40_LOCAL',record_type='MATCHED_WINDOW',track='T004',map_token=top['map_token'],
        map_part=top['map_part'],first_frame=frames[0]['frame'],last_frame=frames[-1]['frame'],
        first_time_s=frames[0]['time_s'],last_time_s=frames[-1]['time_s'],observed_frames=len(frames),
        frames_above_reference=above,max_anomaly_score=top['anomaly_score'],max_anomaly_frame=top['frame'],
        anomaly_threshold=top['anomaly_threshold'],effective_coverage=None,coverage_gate='UNKNOWN',
        multi_frame_evidence=evidence,local_diagnostic='WITHIN_REFERENCE' if not above else 'ABOVE_REFERENCE_PRESENT',
        final_decision=decide('UNKNOWN',bool(above),evidence),review_priority='STANDARD',
        reason='已匹配局部段可做横向筛查，整体有效观测覆盖率未知。')
    support_by_id = keyed(scored,lambda r:r['candidate_id'])
    cases = [window]
    for source in lane_candidates:
        event = source['event_id']
        score = support_by_id[event]
        if score['evidence_family'] != 'LANE_MARKING_GEOMETRY' or int(score['observed_frames']) != int(source['observed_frames']):
            raise ValueError(f'Candidate evidence mismatch: {event}')
        priority = 'PRIORITY' if score['evidence_level']=='HIGH_EVIDENCE' else 'STANDARD'
        cases.append(dict(record_id=event,record_type='UNMATCHED_LANE_CANDIDATE',track=source['track_id'],map_token=None,
            first_frame=int(source['first_frame']),last_frame=int(source['last_frame']),first_time_s=float(source['first_time_s']),
            last_time_s=float(source['last_time_s']),observed_frames=int(source['observed_frames']),
            effective_coverage=None,coverage_gate='UNKNOWN',max_anomaly_score=None,frames_above_reference=None,
            upstream_support_frames=int(score['support_frames']),upstream_evidence_level=score['evidence_level'],
            upstream_evidence_score=float(score['evidence_score']),context_flags=source['context_flags'],
            unsigned_distance_m=float(source['map_distance_median_m']),
            bbox_xy_m=[float(source[k]) for k in ('bbox_x_min_m','bbox_y_min_m','bbox_x_max_m','bbox_y_max_m')],
            multi_frame_evidence='UPSTREAM_CANDIDATE_SUPPORT',local_diagnostic='NOT_SCORABLE',
            final_decision=decide('UNKNOWN',None,'UPSTREAM_CANDIDATE_SUPPORT'),review_priority=priority,
            reason='缺少可靠的地图线对应，无法计算带符号横向异常分数。有效观测覆盖率未知。'))
    return dict(scene='scene-0980',scope='lane-marking synthesis from one drive',decision_labels=LABELS,
        summary=dict(matched_windows=1,unmatched_lane_candidates=len(lane_candidates),matched_test_frames=len(frames),
            matched_test_frames_above_reference=above,insufficient_evidence_cases=sum(c['final_decision']=='INSUFFICIENT_EVIDENCE' for c in cases),
            priority_review_cases=sum(c['review_priority']=='PRIORITY' for c in cases),
            occupancy_candidates_outside_scope=sum(r['evidence_family']=='ROAD_OCCUPANCY' for r in scored)),
        cases=cases,matched_frame_evidence=frames,
        limitations=['有效覆盖率未知，几何可用比例只描述已检出的点。','异常阈值是同一次行驶内的经验参考。',
                     '多帧记录来自同一次行驶。占道候选另供通行复核。'])


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('zip_file',type=Path)
    for flag in ('anomaly','quality','scored'):
        parser.add_argument('--'+flag,type=Path,required=True)
    parser.add_argument('--output',type=Path,default=Path('M3_scene0980_reliability_synthesis.json'))
    args=parser.parse_args()
    with ZipFile(args.zip_file) as archive:
        result=synthesize(read_csv(args.anomaly),read_csv(args.quality),read_zip(archive,'scene0980_sensor_hdmap_line_metrics.csv'),
                          read_zip(archive,'scene0980_discrepancy_candidates_v1.csv'),read_csv(args.scored))
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text(json.dumps(result,ensure_ascii=False,indent=2,allow_nan=False)+'\n',encoding='utf-8')
    print(json.dumps(result['summary'],ensure_ascii=False))


if __name__=='__main__':
    main()
